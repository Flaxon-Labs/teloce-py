"""Small dependency-aware ES module bundler for generated Teloce modules."""

from __future__ import annotations

import re
from pathlib import Path
from typing import Dict, List, Set


class BundleError(RuntimeError):
    """Raised when a requested production bundle cannot be resolved."""


class ModuleBundler:
    """Bundle generated component modules without requiring npm tooling.

    Teloce-generated modules have a deliberately small export contract. Each
    module is wrapped in a private scope, imports are converted to references
    to already-evaluated dependency modules, and the entry module's public
    exports are re-exported from the bundle.
    """

    _DEFAULT_IMPORT = re.compile(
        r'import\s+([A-Za-z_$][\w$]*)\s+from\s+["\']([^"\']+)["\'];?'
    )
    _NAMED_IMPORT = re.compile(
        r'import\s*\{([^}]+)\}\s*from\s+["\']([^"\']+)["\'];?'
    )
    _NAMESPACE_IMPORT = re.compile(
        r'import\s+\*\s+as\s+([A-Za-z_$][\w$]*)\s+from\s+["\']([^"\']+)["\'];?'
    )

    def __init__(self, output_dir: str | Path):
        self.output_dir = Path(output_dir).resolve()

    def bundle(self, entry: str | Path, output: str | Path | None = None) -> Path:
        entry_path = self._resolve_entry(entry)
        modules: List[Path] = []
        visiting: Set[Path] = set()
        visited: Set[Path] = set()

        def visit(path: Path) -> None:
            path = path.resolve()
            if path in visiting:
                cycle = " -> ".join(str(item.relative_to(self.output_dir)) for item in (*visiting, path))
                raise BundleError(f"Circular bundle dependency: {cycle}")
            if path in visited:
                return
            if not path.is_file():
                raise BundleError(f"Bundle module not found: {path}")
            visiting.add(path)
            source = path.read_text(encoding="utf-8")
            for specifier in self._imports(source):
                if specifier.startswith("."):
                    visit(self._resolve_import(path, specifier))
            visiting.remove(path)
            visited.add(path)
            modules.append(path)

        visit(entry_path)
        output_path = Path(output) if output else entry_path.with_name(entry_path.stem + ".bundle.js")
        if not output_path.is_absolute():
            output_path = self.output_dir / output_path
        output_path.parent.mkdir(parents=True, exist_ok=True)

        chunks = ["// Generated by Teloce-Py production bundler", "const __teloce_modules = {};", ""]
        for path in modules:
            chunks.append(self._wrap(path))
        entry_key = self._key(entry_path)
        chunks.extend([
            f'const __teloce_entry = __teloce_modules[{entry_key!r}];',
            'export const mount = __teloce_entry.mount;',
            'export const createApp = __teloce_entry.createApp || __teloce_entry.mount;',
            'export default __teloce_entry.default;',
        ])
        output_path.write_text("\n".join(chunks) + "\n", encoding="utf-8")
        return output_path

    def _resolve_entry(self, entry: str | Path) -> Path:
        candidate = Path(entry)
        if not candidate.is_absolute():
            candidate = self.output_dir / candidate
        return candidate.with_suffix(".js") if candidate.suffix == "" else candidate

    def _resolve_import(self, parent: Path, specifier: str) -> Path:
        candidate = (parent.parent / specifier).resolve()
        if candidate.suffix == "":
            candidate = candidate.with_suffix(".js")
        try:
            candidate.relative_to(self.output_dir)
        except ValueError as exc:
            raise BundleError(f"Bundle import escapes output directory: {specifier}") from exc
        return candidate

    def _imports(self, source: str) -> List[str]:
        return [* (match.group(2) for match in self._DEFAULT_IMPORT.finditer(source)),
                * (match.group(2) for match in self._NAMED_IMPORT.finditer(source)),
                * (match.group(2) for match in self._NAMESPACE_IMPORT.finditer(source))]

    def _key(self, path: Path) -> str:
        return path.resolve().relative_to(self.output_dir).as_posix()

    def _wrap(self, path: Path) -> str:
        source = path.read_text(encoding="utf-8")
        current_key = self._key(path)
        named_exports = sorted(set(re.findall(
            r'\bexport\s+(?:async\s+)?(?:const|let|var|function|class)\s+([A-Za-z_$][\w$]*)',
            source,
        )))

        def default_import(match: re.Match[str]) -> str:
            name, specifier = match.groups()
            if not specifier.startswith("."):
                raise BundleError(f"External import cannot be bundled without a resolver: {specifier}")
            dependency = self._key(self._resolve_import(path, specifier))
            return f'const {name} = __teloce_modules[{dependency!r}].default;'

        source = self._DEFAULT_IMPORT.sub(default_import, source)

        def namespace_import(match: re.Match[str]) -> str:
            name, specifier = match.groups()
            if not specifier.startswith("."):
                raise BundleError(f"External import cannot be bundled without a resolver: {specifier}")
            dependency = self._key(self._resolve_import(path, specifier))
            return f'const {name} = __teloce_modules[{dependency!r}];'

        source = self._NAMESPACE_IMPORT.sub(namespace_import, source)

        def named_import(match: re.Match[str]) -> str:
            bindings, specifier = match.groups()
            if not specifier.startswith("."):
                raise BundleError(f"External import cannot be bundled without a resolver: {specifier}")
            dependency = self._key(self._resolve_import(path, specifier))
            declarations = []
            for binding in bindings.split(','):
                parts = re.split(r'\s+as\s+', binding.strip())
                imported = parts[0].strip()
                local = parts[-1].strip()
                if imported:
                    declarations.append(f'const {local} = __teloce_modules[{dependency!r}].{imported};')
            return " ".join(declarations)

        source = self._NAMED_IMPORT.sub(named_import, source)
        source = re.sub(r'(^|\n)\s*export\s+default\s+__component\s*;?', r'\1', source)
        source = re.sub(r'(^|\n)(\s*)export\s+(function|const|let|var)\s+', r'\1\2\3 ', source)
        exported_names = ", " + ", ".join(f"{name}: {name}" for name in named_exports) if named_exports else ""
        return "\n".join([
            f'__teloce_modules[{current_key!r}] = (() => {{',
            source,
            f'return {{ default: (typeof __component !== "undefined" ? __component : undefined), mount: (typeof mount === "function" ? mount : undefined), createApp: (typeof createApp === "function" ? createApp : (typeof mount === "function" ? mount : undefined)){exported_names} }};',
            '})();',
            '',
        ])
